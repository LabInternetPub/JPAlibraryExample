package cat.tecnocampus.library.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

import java.time.Instant;
import java.util.List;
import java.util.Objects;
import java.util.UUID;

/**
 * A physical copy of a book on a shelf of a branch.
 *
 * <p>The copy row alone answers "is it available?": it carries the reservation that holds it and
 * until when. That keeps the availability check and the lock on one single row, and keeps the
 * row small. The copy has no collection of its loans or reservations for the same reason.
 */
@Entity
@Table(name = "book_copy", uniqueConstraints =
        @UniqueConstraint(name = "uk_copy_branch_barcode", columnNames = {"branch_id", "barcode"}))
public class Copy {

    // Assigned here, not generated by the database: the id exists before the row does. It also
    // means Spring Data's save() cannot tell a new copy from an existing one (see the import lesson).
    @Id
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    private Branch branch;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    private Book book;

    @Column(nullable = false)
    private String barcode;

    @Column(name = "floor_number", nullable = false)
    private int floor;

    @Column(nullable = false)
    private String shelf;

    @Enumerated(EnumType.STRING)
    @Column(name = "copy_condition", nullable = false)
    private Condition condition;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private CopyStatus status;

    // Who holds the copy and until when are private: they are never part of a public response.
    private UUID reservationId;

    private Instant reservedUntil;

    protected Copy() {
    }

    public Copy(Branch branch, Book book, String barcode, int floor, String shelf, Condition condition) {
        this.id = UUID.randomUUID();
        this.branch = Objects.requireNonNull(branch);
        this.book = Objects.requireNonNull(book);
        this.barcode = Objects.requireNonNull(barcode);
        this.floor = floor;
        this.shelf = Objects.requireNonNull(shelf);
        this.condition = Objects.requireNonNull(condition);
        this.status = CopyStatus.AVAILABLE;
    }

    /**
     * A reservation whose deadline has passed no longer holds the copy, even if nothing has
     * cleaned it up yet: expiry is decided when reading, with the request's clock.
     */
    public boolean isAvailableAt(Instant now) {
        return status == CopyStatus.AVAILABLE
                || status == CopyStatus.RESERVED && reservedUntil != null && !now.isBefore(reservedUntil);
    }

    /** The status the public may see: an expired reservation shows as available. */
    public CopyStatus visibleStatusAt(Instant now) {
        return isAvailableAt(now) ? CopyStatus.AVAILABLE : status;
    }

    /**
     * Guards its own state, but only against the state this object has in memory. If another
     * transaction reserved the copy after this object was read, the check still passes: the guard
     * is only as good as the read that loaded the object (see the reservation lesson).
     */
    public void reserve(UUID reservationId, Instant until, Instant now) {
        if (!isAvailableAt(now)) {
            throw new CopiesUnavailableException(List.of(id));
        }
        this.status = CopyStatus.RESERVED;
        this.reservationId = Objects.requireNonNull(reservationId);
        this.reservedUntil = Objects.requireNonNull(until);
    }

    public void lend(Instant now) {
        if (!isAvailableAt(now)) {
            throw new CopiesUnavailableException(List.of(id));
        }
        this.status = CopyStatus.ON_LOAN;
        this.reservationId = null;
        this.reservedUntil = null;
    }

    public void returnToShelf() {
        if (status != CopyStatus.ON_LOAN) {
            throw new IllegalStateException("Only a copy on loan can be returned");
        }
        this.status = CopyStatus.AVAILABLE;
    }

    public void withdraw() {
        this.status = CopyStatus.WITHDRAWN;
        this.reservationId = null;
        this.reservedUntil = null;
    }

    /**
     * Re-importing the catalogue changes only the physical attributes: the copy keeps its id and
     * its status. Only real changes are written, so dirty checking issues an UPDATE only for the
     * copies that actually changed.
     *
     * @return true if an attribute changed
     */
    public boolean reimport(int floor, String shelf, Condition condition) {
        boolean changed = this.floor != floor || !this.shelf.equals(shelf) || this.condition != condition;
        if (changed) {
            this.floor = floor;
            this.shelf = Objects.requireNonNull(shelf);
            this.condition = Objects.requireNonNull(condition);
        }
        return changed;
    }

    public UUID getId() {
        return id;
    }

    public Branch getBranch() {
        return branch;
    }

    public Book getBook() {
        return book;
    }

    public String getBarcode() {
        return barcode;
    }

    public int getFloor() {
        return floor;
    }

    public String getShelf() {
        return shelf;
    }

    public Condition getCondition() {
        return condition;
    }

    public CopyStatus getStatus() {
        return status;
    }

    public UUID getReservationId() {
        return reservationId;
    }

    public Instant getReservedUntil() {
        return reservedUntil;
    }
}
